#!/usr/bin/env python3
"""Write data/talents.js: the druid talent trees from Wowhead's Forever talent calculator.

Trees are in talent-string order (Balance, Feral Combat, Restoration), talents row by row then column by column.

    python tools/build_talents.py [--sim-tree path/to/ui/sim/talents/trees/druid.json]
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

URL = 'https://nether.wowhead.com/forever/data/talents-classic'
TREES = [('283', 'Balance', 'balance'), ('281', 'Feral Combat', 'feral'), ('282', 'Restoration', 'resto')]
ROOT = Path(__file__).resolve().parent.parent


def fetch_page_data():
    request = urllib.request.Request(URL, headers={'User-Agent': 'Mozilla/5.0 druid-guide'})
    text = urllib.request.urlopen(request).read().decode('utf-8')
    start = text.index('{', text.index('setPageData('))
    data, _ = json.JSONDecoder().raw_decode(text, start)
    return data


def one_line(text):
    return re.sub(r'\s+', ' ', text).strip()


def build_tree(data, tab, name, key):
    raw = sorted(data['talents'][tab].values(), key=lambda t: (t['row'], t['col']))
    position = {t['id']: (t['row'], t['col']) for t in raw}
    talents = []
    for t in raw:
        prerequisite = t['requires'][0] if t['requires'] else None
        talents.append({
            'row': t['row'], 'col': t['col'], 'max': len(t['ranks']), 'name': t['name'], 'icon': t['icon'],
            'spell': t['ranks'][0],
            'ranks': [one_line(t['descriptions'][str(rank + 1)]) for rank in range(len(t['ranks']))],
            'req': {'row': position[prerequisite['id']][0], 'col': position[prerequisite['id']][1],
                    'qty': prerequisite['qty']} if prerequisite else None,
            'reqPoints': t['requiredPoints'],
        })
    return {'key': key, 'name': name,
            'bg': f'https://wow.zamimg.com/images/wow/talents/backgrounds/tbc/{tab}.jpg', 'talents': talents}


def mismatches_with_sim(trees, sim_tree_path):
    sim_trees = json.loads(Path(sim_tree_path).read_text(encoding='utf-8'))
    problems = []
    for ours, theirs in zip(trees, sim_trees):
        sim_talents = sorted(theirs['talents'], key=lambda t: (t['location']['rowIdx'], t['location']['colIdx']))
        if len(sim_talents) != len(ours['talents']):
            problems.append(f"{ours['name']}: {len(ours['talents'])} talents on Wowhead, {len(sim_talents)} in the sim")
            continue
        for a, b in zip(ours['talents'], sim_talents):
            if (a['name'], a['max']) != (b['fancyName'], b['maxPoints']):
                problems.append(f"{ours['name']}: {a['name']} x{a['max']} vs {b['fancyName']} x{b['maxPoints']}")
    return problems


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--sim-tree', default=None)
    parser.add_argument('--out', default=str(ROOT / 'data' / 'talents.js'))
    args = parser.parse_args()

    data = fetch_page_data()
    trees = [build_tree(data, *tree) for tree in TREES]

    if args.sim_tree:
        problems = mismatches_with_sim(trees, args.sim_tree)
        if problems:
            sys.exit('Wowhead and the sim disagree:\n' + '\n'.join(problems))

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps({'hashVersion': data['hashVersion'], 'trees': trees}, separators=(',', ':'), ensure_ascii=False)
    out.write_text("// Generated by tools/build_talents.py from Wowhead's Forever talent calculator. Do not edit by hand.\n"
                   f'window.TALENTS = {payload};\n', encoding='utf-8')
    print(out, data['hashVersion'], [len(t['talents']) for t in trees])


if __name__ == '__main__':
    main()
